SAMPLE_CATALYSIS_STUDY = """
Title: Photocatalytic Degradation of Methylene Blue Using TiO2/Graphene
Nanocomposites Under Visible Light Irradiation

Abstract:
TiO2/graphene oxide (GO) nanocomposites were synthesized via a hydrothermal
method for enhanced photocatalytic degradation of methylene blue dye.
Titanium(IV) isopropoxide was used as the TiO2 precursor, and graphene oxide
was prepared by the modified Hummers method from natural graphite flakes.

Synthesis:
GO was dispersed in deionized water (2 mg/mL) by sonication for 1 h.
Titanium(IV) isopropoxide (5 mL) was added dropwise to the GO suspension
under stirring at room temperature. The mixture was transferred to a
100 mL Teflon-lined stainless steel autoclave and heated at 180 °C for
12 h. The product was collected by centrifugation at 8000 rpm for 10 min,
washed with ethanol and deionized water, and dried at 80 °C for 24 h.

Characterization:
XRD patterns were recorded on a Rigaku MiniFlex 600 with Cu Kα radiation.
Raman spectroscopy was performed using a Horiba LabRAM HR Evolution with
a 532 nm laser excitation. UV-Vis diffuse reflectance spectra were collected
on a Shimadzu UV-2600 spectrophotometer equipped with an integrating sphere.
BET surface area analysis was conducted on a Micromeritics ASAP 2020 using
N2 adsorption-desorption isotherms at 77 K. X-ray photoelectron spectroscopy
(XPS) was performed on a Kratos Axis Ultra DLD with a monochromated Al Kα
source (1486.6 eV).

Photocatalytic Testing:
Photocatalytic experiments were conducted in a 250 mL Pyrex glass reactor.
The catalyst (50 mg) was dispersed in 100 mL of methylene blue solution
(10 mg/L). The suspension was stirred in the dark for 30 min to achieve
adsorption-desorption equilibrium. A 300 W Xe lamp equipped with a 420 nm
cutoff filter was used as the visible light source. Aliquots (3 mL) were
withdrawn at regular intervals and centrifuged to remove the catalyst.
The concentration of methylene blue was monitored by UV-Vis absorption
at 664 nm.

Cyclic voltammetry (CV) was performed on a CHI 660E electrochemical
workstation using a three-electrode system with Ag/AgCl reference electrode
and Pt counter electrode. Electrochemical impedance spectroscopy (EIS) was
measured in the frequency range of 0.01 Hz to 100 kHz with an AC amplitude
of 10 mV.

Results:
The TiO2/GO nanocomposites showed 95% degradation of methylene blue within
60 min under visible light, compared to 45% for bare TiO2. The enhanced
activity is attributed to the reduced bandgap (2.8 eV vs 3.2 eV for pure
TiO2) and improved charge separation facilitated by the graphene support.
BET surface area increased from 55 m2/g for pure TiO2 to 128 m2/g for
the composite. The material maintained >90% efficiency after 5 cycles,
demonstrating excellent stability.
"""

